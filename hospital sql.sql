create database hospital_mange 
use hospital_mange 
CREATE TABLE Patients (
 PatientID INT PRIMARY KEY AUTO_INCREMENT,
 FirstName VARCHAR(50),
 LastName VARCHAR(50), 
 Gender VARCHAR(10),
 DOB DATE, 
 Phone VARCHAR(15), 
 Address VARCHAR(200),
 BloodGroup VARCHAR(5)
 );
 
 CREATE TABLE Doctors ( 
 DoctorID INT PRIMARY KEY AUTO_INCREMENT, 
 DoctorName VARCHAR(100), 
 Specialization VARCHAR(100), 
 Phone VARCHAR(15), 
 Email VARCHAR(100), 
 Experience INT );
 
 CREATE TABLE Departments (
 DepartmentID INT PRIMARY KEY AUTO_INCREMENT,
 DepartmentName VARCHAR(100), 
 Location VARCHAR(100) );
 
 CREATE TABLE DoctorDepartment ( 
 DoctorID INT, 
 DepartmentID INT, 
 PRIMARY KEY (DoctorID, DepartmentID), 
 FOREIGN KEY (DoctorID) REFERENCES Doctors(DoctorID), 
 FOREIGN KEY (DepartmentID) REFERENCES Departments(DepartmentID) 
 );
 
 CREATE TABLE Appointments ( 
 AppointmentID INT PRIMARY KEY AUTO_INCREMENT,
 PatientID INT, 
 DoctorID INT, 
 AppointmentDate DATE, 
 AppointmentTime TIME, 
 Status VARCHAR(30), 
 FOREIGN KEY (PatientID) REFERENCES Patients(PatientID), 
 FOREIGN KEY (DoctorID) REFERENCES Doctors(DoctorID) 
 );
 
 CREATE TABLE Rooms ( 
 RoomID INT PRIMARY KEY AUTO_INCREMENT, 
 RoomNumber VARCHAR(20),
 RoomType VARCHAR(50), 
 Status VARCHAR(30)
 );
 
 CREATE TABLE Admissions (
 AdmissionID INT PRIMARY KEY AUTO_INCREMENT,
 PatientID INT,
 RoomID INT, 
 AdmissionDate DATE,
 DischargeDate DATE, 
 FOREIGN KEY (PatientID) REFERENCES Patients(PatientID), 
 FOREIGN KEY (RoomID) REFERENCES Rooms(RoomID) 
 );
 
 CREATE TABLE Nurses (
 NurseID INT PRIMARY KEY AUTO_INCREMENT, 
 NurseName VARCHAR(100),
 Phone VARCHAR(15), 
 Shift VARCHAR(20)
 );
 
 CREATE TABLE NurseAssignment (
 AssignmentID INT PRIMARY KEY AUTO_INCREMENT,
 NurseID INT, 
 PatientID INT, 
 AssignmentDate DATE,
 FOREIGN KEY (NurseID) REFERENCES Nurses(NurseID), 
 FOREIGN KEY (PatientID) REFERENCES Patients(PatientID)
 );
 
 
 CREATE TABLE Medicines (
 MedicineID INT PRIMARY KEY AUTO_INCREMENT,
 MedicineName VARCHAR(100), 
 Price DECIMAL(10,2),
 Stock INT 
 );
 
 CREATE TABLE Prescriptions ( 
 PrescriptionID INT PRIMARY KEY AUTO_INCREMENT, 
 PatientID INT, 
 DoctorID INT, 
 MedicineID INT,
 Dosage VARCHAR(100),
 Duration VARCHAR(50), 
 FOREIGN KEY (PatientID) REFERENCES Patients(PatientID), 
 FOREIGN KEY (DoctorID) REFERENCES Doctors(DoctorID), 
 FOREIGN KEY (MedicineID) REFERENCES Medicines(MedicineID) 
 );
 
 CREATE TABLE LaboratoryTests ( 
 TestID INT PRIMARY KEY AUTO_INCREMENT,
 PatientID INT,
 DoctorID INT, 
 TestName VARCHAR(100), 
 TestDate DATE, 
 Result VARCHAR(200), 
 FOREIGN KEY (PatientID) REFERENCES Patients(PatientID), 
 FOREIGN KEY (DoctorID) REFERENCES Doctors(DoctorID)
 );
 
 CREATE TABLE Billing ( 
 BillID INT PRIMARY KEY AUTO_INCREMENT,
 PatientID INT, 
 AdmissionID INT, 
 TotalAmount DECIMAL(10,2), 
 BillDate DATE,
 FOREIGN KEY (PatientID) REFERENCES Patients(PatientID), 
 FOREIGN KEY (AdmissionID) REFERENCES Admissions(AdmissionID)
 );
 
 CREATE TABLE Payments ( 
 PaymentID INT PRIMARY KEY AUTO_INCREMENT, 
 BillID INT,
 PaymentDate DATE,
 Amount DECIMAL(10,2), 
 PaymentMethod VARCHAR(50), 
 FOREIGN KEY (BillID) REFERENCES Billing(BillID) 
 );
 
 CREATE TABLE Staff (
 StaffID INT PRIMARY KEY AUTO_INCREMENT, 
 StaffName VARCHAR(100),
 Role VARCHAR(50), 
 Phone VARCHAR(15), 
 Salary DECIMAL(10,2) 
 );
 
